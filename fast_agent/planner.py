"""LLM Task Planning Module for FastAgent.

Decomposes arbitrary natural language user instructions into structured,
executable multi-step plans using the loaded LLM/VLM model without any fragile regexes.
"""

from __future__ import annotations

import json
import logging
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional

from openai import OpenAI

from fast_agent.config import AgentConfig

logger = logging.getLogger(__name__)

PLANNER_SYSTEM_PROMPT = """You are an expert Android Automation Task Planner.
Analyze the user instruction and decompose it into an actionable multi-step plan.
Respond ONLY with a valid JSON object in this exact schema, with NO markdown formatting, NO code blocks, and NO other text:
{
  "target_app": "<Primary application name, e.g. eBay, Vinted, Subito, Settings, or null>",
  "search_query": "<Specific query or search term extracted from instruction, or null>",
  "intent_category": "<marketplace_search | settings | note | media_search | generic>",
  "steps": [
    "1. Step description",
    "2. Step description"
  ]
}
"""


@dataclass
class TaskPlan:
    """Structured plan generated by the LLM."""
    target_app: Optional[str] = None
    search_query: Optional[str] = None
    intent_category: str = "generic"
    steps: List[str] = field(default_factory=list)
    raw_response: str = ""

    @property
    def formatted_plan(self) -> str:
        """Numbered plain text plan suitable for feeding into VLM prompts."""
        if not self.steps:
            return ""
        return "\n".join(self.steps)


class TaskPlanner:
    """Uses LLM fast text completion to decompose instructions into structured plans."""

    def __init__(self, config: Optional[AgentConfig] = None) -> None:
        self.config = config or AgentConfig()
        self.client = OpenAI(
            base_url=self.config.vllm_base_url,
            api_key=self.config.vllm_api_key,
            timeout=15.0,
        )
        self.model_name = self.config.model_name

    def plan(self, instruction: str) -> TaskPlan:
        """Decompose user instruction into structured plan using LLM."""
        if not instruction or not instruction.strip():
            return TaskPlan()

        try:
            resp = self.client.chat.completions.create(
                model=self.model_name,
                messages=[
                    {"role": "system", "content": PLANNER_SYSTEM_PROMPT},
                    {"role": "user", "content": instruction.strip()},
                ],
                temperature=0.0,
                max_tokens=350,
            )
            raw = (resp.choices[0].message.content or "").strip()

            clean_json = raw
            if "```" in clean_json:
                start = clean_json.find("{")
                end = clean_json.rfind("}")
                if start != -1 and end != -1:
                    clean_json = clean_json[start : end + 1]

            data = json.loads(clean_json)
            target_app = data.get("target_app")
            if target_app and str(target_app).lower() in ["null", "none", ""]:
                target_app = None

            search_query = data.get("search_query")
            if search_query and str(search_query).lower() in ["null", "none", ""]:
                search_query = None

            intent_category = str(data.get("intent_category", "generic")).lower()
            raw_steps = data.get("steps", [])
            steps: List[str] = []
            if isinstance(raw_steps, list):
                for s in raw_steps:
                    if isinstance(s, str) and s.strip():
                        steps.append(s.strip())

            return TaskPlan(
                target_app=target_app,
                search_query=search_query,
                intent_category=intent_category,
                steps=steps,
                raw_response=raw,
            )
        except Exception as e:
            logger.warning("LLM planning fallback due to error: %s", e)
            return TaskPlan(
                target_app=None,
                search_query=None,
                intent_category="generic",
                steps=[f"1. Execute instruction: {instruction}"],
                raw_response=str(e),
            )
